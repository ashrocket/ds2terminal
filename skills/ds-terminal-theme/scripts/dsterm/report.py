"""report.py - report.json and report.md for the generated themes."""
import json
from typing import List

from . import character as CH
from . import claudecode as CC
from . import colorlab as cl
from .theme import TERMINAL_KEY

GATE_ORDER = ("fg_contrast", "halation", "ansi_normal", "ansi_bright", "bright_relation", "dim_brightBlack",
              "grays_dark", "inks_light", "separation", "cvd", "selection", "cursor", "bold", "text_on_color", "hue_vs_text", "faint_text", "translucency")
SLOT_ORDER = ["background", "foreground", "bold", "cursor", "selection"] + list(range(16))


def slot_label(k) -> str:
    return cl.ANSI_NAMES[k] if isinstance(k, int) else k


def theme_record(name: str, file: str, th: dict) -> dict:
    slots = th["slots"]
    bg = slots["background"].hex
    rows = []
    toks = th.get("token_hex") or {}
    for k in SLOT_ORDER:
        s = slots[k]
        rows.append({"slot": slot_label(k), "key": TERMINAL_KEY[k], "hex": s.hex, "source": s.source,
                     "token_hex": toks.get(s.source[6:]) if s.source.startswith("token:") else None,
                     "origin": s.origin, "changed_from": s.original if s.original != s.hex else None,
                     "apca_lc": round(cl.lc_abs(s.hex, bg), 1) if k != "background" else None,
                     "wcag": round(cl.contrast_ratio(s.hex, bg), 2) if k != "background" else None,
                     "note": s.note})
    res = th["check"]
    gates = []
    applies = {"halation": th["mode"] == "dark", "grays_dark": th["mode"] == "dark", "inks_light": th["mode"] == "light"}
    for g in GATE_ORDER:
        if not applies.get(g, True):
            continue
        if g == "translucency":
            gates.append(translucency_row(res, th.get("alpha", 1.0)))
            continue
        fails = [f["detail"] for f in res["failures"] if f["id"] == g]
        misses = [m["detail"] for m in res["misses"] if m["id"] == g]
        gates.append({"gate": g, "pass": not fails, "failures": fails, "target_misses": misses})
    before = th.get("before") or {}
    rec = {"name": name, "file": file, "mode": th["mode"], "derived": th["derived"], "pass": res["pass"],
            "background_alpha": th.get("alpha", 1.0),
            "failed_gates": res["failed_gate_ids"], "failed_before_repair": before.get("failed_gate_ids", []),
            "metrics": res["metrics"], "slots": rows, "gates": gates, "repairs": th["repairs"],
            "brand": th["brand"], "brand_hex": th["brand_hex"], "assignment": th["assignment"],
            "notes": th["notes"], "unused_tokens": th["unused_tokens"]}
    rec["character"] = CH.character(rec)
    rec["claude_code"] = CC.pairing(rec)
    return rec


def translucency_row(res: dict, alpha: float) -> dict:
    """One report row for the background alpha. Translucent: the worst case over the desktops."""
    if alpha >= 1.0:
        return {"gate": "translucency", "pass": True, "failures": [],
                "target_misses": [], "info": "opaque (alpha 1, blur 0)"}
    fails = ["%s: %s" % (f["id"], f["detail"]) for f in res["failures"] if f.get("desktop")]
    rows = res["metrics"].get("translucency", {}).get("desktops", [])
    parts = []
    for r in rows:
        p = "over %s (bg %s): fg Lc %s, weakest normal Lc %s, weakest bright Lc %s" % (
            r["desktop"], r["background"], r.get("fg_lc"), r.get("min_normal_lc"), r.get("min_bright_lc"))
        if "faint_fg_lc" in r:
            p += ", faint fg Lc %s, weakest faint color Lc %s" % (r["faint_fg_lc"], r.get("faint_ansi_min_lc"))
        parts.append(p)
    return {"gate": "translucency", "pass": not fails, "failures": fails, "target_misses": [],
            "info": "alpha %.2f, blur 0; worst case %s" % (alpha, "; ".join(parts))}


def write_json(path: str, data: dict) -> None:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)


def _md_escape(s) -> str:
    """Text for a Markdown table cell: no raw HTML, no table or code-span breaks."""
    s = str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("|", "\\|").replace("`", "'").replace("\r", " ").replace("\n", " ")
    return s.replace("*", "\\*").replace("_", "\\_")


def to_markdown(data: dict) -> str:
    L: List[str] = []
    L.append("# %s: Terminal themes" % _md_escape(data["name"]))
    L.append("")
    L.append("Generated by ds2terminal %s. Sources: %s." % (data["version"], _md_escape(", ".join(data["sources"]))))
    L.append("")
    allpass = all(t["pass"] for t in data["themes"])
    L.append("**Result: %s.**" % ("every hard gate passes for every theme" if allpass else "SOME GATES FAIL"))
    L.append("")
    L.append("| Theme | Mode | Derived | Gates | Repairs |")
    L.append("|---|---|---|---|---|")
    for t in data["themes"]:
        L.append("| %s | %s | %s | %s | %d |" % (_md_escape(t["file"]), t["mode"], "yes" if t["derived"] else "no",
                                               "all pass" if t["pass"] else "FAIL: " + ", ".join(t["failed_gates"]),
                                               len(t["repairs"])))
    L.append("")
    L.append("Font: %s %s pt. %s" % (_md_escape(data["font"]["postscript"]), data["font"]["size"], _md_escape(data["font"]["note"])))
    L.append("")
    if data.get("notes"):
        L.append("## Notes")
        L.append("")
        for n in data["notes"]:
            L.append("- %s" % _md_escape(n))
        L.append("")
    for t in data["themes"]:
        L.append("## %s" % _md_escape(t["file"]))
        L.append("")
        L.append("Mode: %s%s. Brand color: %s %s." % (t["mode"], " (derived from the other mode)" if t["derived"] else "",
                                                     _md_escape(t["brand"] or "none"), t["brand_hex"] or ""))
        L.append("")
        L.append("| Slot | Hex | Source | APCA Lc | WCAG | Note |")
        L.append("|---|---|---|---|---|---|")
        for r in t["slots"]:
            L.append("| %s | `%s` | %s | %s | %s | %s |" % (r["slot"], r["hex"], _md_escape(r["source"]),
                                                          "" if r["apca_lc"] is None else r["apca_lc"],
                                                          "" if r["wcag"] is None else r["wcag"], _md_escape(r["note"])))
        L.append("")
        L.append("| Gate | Result | Detail |")
        L.append("|---|---|---|")
        for g in t["gates"]:
            det = "; ".join(g["failures"]) if g["failures"] else ("target: " + "; ".join(g["target_misses"]) if g["target_misses"] else "")
            if g.get("info"):
                det = g["info"] + ("; " + det if det else "")
            L.append("| %s | %s | %s |" % (g["gate"], "pass" if g["pass"] else "**FAIL**", _md_escape(det)))
        L.append("")
        if t["failed_before_repair"]:
            L.append("Gates that failed before repair: %s." % ", ".join(t["failed_before_repair"]))
            L.append("")
        if t["repairs"]:
            L.append("Repairs:")
            L.append("")
            for r in t["repairs"]:
                L.append("- %s" % _md_escape(r))
            L.append("")
        if t["notes"]:
            for n in t["notes"]:
                L.append("- %s" % _md_escape(n))
            L.append("")
        if t.get("character"):
            L.extend(CH.markdown_lines(t["character"]))
            L.append("")
        if t.get("claude_code"):
            L.extend(CC.markdown_lines(t["claude_code"]))
            L.append("")
    if data.get("ignored_tokens"):
        L.append("## Tokens left out")
        L.append("")
        L.append(", ".join("`%s`" % _md_escape(x) for x in data["ignored_tokens"]))
        L.append("")
    L.append("## How to read this report")
    L.append("")
    L.append("- APCA Lc and WCAG are measured against the background. The gates are in `colorlab.GATES`.")
    L.append("- \"source\" names the design-system token, or says `synthesized`, `derived:...`, `alias:...` or `override`.")
    L.append("- A repair changes a color only to pass a hard gate. The report lists each change.")
    L.append("- \"Character\" rows are targets, not gates. They show how much of the design system the theme keeps.")
    L.append("- \"Claude Code\" rows show the contrast of the pairs that Claude Code draws, for its ANSI theme and its standard theme.")
    L.append("")
    return "\n".join(L)
